"""Property-based tests for avatar-upload soundness (Correctness Property 6).

**Validates: Requirements 10.5**

Correctness Property 6 (Upload-soundness), from
``.kiro/specs/security-hardening-remediation/design.md`` (Workstream 5):

    An upload is persisted **iff** its content-derived type is allowed **and**
    matches the declared type; otherwise no file is written.

The avatar handler (Task 9.1) derives the true image type from the file *content*
via the pure helper ``backend.main._detect_image_type`` (Pillow ``verify()`` with a
magic-byte fallback), rejects when the content-derived type is missing/disallowed
(``INVALID_IMAGE_CONTENT`` / ``INVALID_IMAGE_TYPE``) or does not match the
client-declared ``Content-Type`` (``IMAGE_TYPE_MISMATCH``), and writes to a single
``main.AVATAR_DIR`` (Task 9.3).

Two complementary properties are encoded:

* ``test_detection_predicate_is_sound`` — pure (no DB). Confirms the detection
  helper is deterministic and *never* yields a type outside the allowed set, which
  is what makes the reference predicate ``derived in ALLOWED and derived == declared``
  well-defined.
* ``test_upload_persists_iff_allowed_and_matching`` — drives the real HTTP endpoint
  and asserts the persistence invariant: a file appears in ``AVATAR_DIR`` for exactly
  the accepted inputs, and the directory is left untouched for every rejected input.

The reference decision is always recomputed by calling the *real* helper
``main._detect_image_type`` on the generated bytes, so the test stays correct
regardless of which detection backend (Pillow vs. magic-byte sniff) is active in the
runtime environment.
"""

import io

import pytest
from hypothesis import HealthCheck
from hypothesis import given
from hypothesis import settings
from hypothesis import strategies as st

import backend.main as main


# ---------------------------------------------------------------------------
# Image byte fixtures
#
# When Pillow is installed the detection helper actually decodes the bytes, so we
# generate genuinely valid 1x1 images. When Pillow is absent the helper falls back
# to a magic-byte sniff, for which well-formed signature prefixes suffice. Either
# way the reference predicate below is computed from the *same* helper, so the test
# remains self-consistent even if a given format fails to encode in this
# environment.
# ---------------------------------------------------------------------------
def _make_image_bytes(fmt: str, fallback_prefix: bytes) -> bytes:
    try:
        from PIL import Image  # type: ignore

        buf = io.BytesIO()
        Image.new("RGB", (1, 1), (200, 30, 30)).save(buf, format=fmt)
        return buf.getvalue()
    except Exception:
        return fallback_prefix


PNG_BYTES = _make_image_bytes("PNG", b"\x89PNG\r\n\x1a\n" + b"\x00" * 32)
JPEG_BYTES = _make_image_bytes("JPEG", b"\xff\xd8\xff\xe0" + b"\x00" * 32)
WEBP_BYTES = _make_image_bytes(
    "WEBP", b"RIFF" + b"\x00\x00\x00\x00" + b"WEBP" + b"\x00" * 16
)
# GIF is a real image format but is NOT in the allowed set, and the helper maps it
# to ``None`` — a useful "valid-looking but unsupported" rejection case.
GIF_BYTES = b"GIF89a\x01\x00\x01\x00\x00\xff\xff\xff,\x00\x00\x00\x00\x01\x00\x01\x00\x00\x02\x02D\x01\x00;"

# A non-empty declared Content-Type is always present in real multipart uploads, so
# the declared-vs-derived equality in the reference predicate is always meaningful.
_DECLARED_TYPES = [
    "image/png",
    "image/jpeg",
    "image/webp",
    "image/gif",
    "text/plain",
    "application/octet-stream",
]

_KNOWN_PAYLOADS = [PNG_BYTES, JPEG_BYTES, WEBP_BYTES, GIF_BYTES]

# Bias the search toward accept cases (matching valid pairs) while still spanning
# mismatches, disallowed types, and arbitrary/garbage bytes.
_matching_pairs = st.sampled_from(
    [
        (PNG_BYTES, "image/png"),
        (JPEG_BYTES, "image/jpeg"),
        (WEBP_BYTES, "image/webp"),
    ]
)
_arbitrary_pairs = st.tuples(
    st.one_of(st.sampled_from(_KNOWN_PAYLOADS), st.binary(min_size=0, max_size=64)),
    st.sampled_from(_DECLARED_TYPES),
)
_upload_strategy = st.one_of(_matching_pairs, _arbitrary_pairs)

AVATAR_URL = "/api/v1/users/me/avatar"
ALLOWED = main.ALLOWED_IMAGE_TYPES


def _reference_accepts(raw: bytes, declared: str) -> bool:
    """Property 6 reference predicate, computed from the real detection helper.

    An upload should persist iff the content-derived type is allowed AND equals
    the client-declared type.
    """
    derived = main._detect_image_type(raw)
    return derived is not None and derived in ALLOWED and derived == declared


# ---------------------------------------------------------------------------
# Property A (pure): the detection helper is deterministic and sound.
# ---------------------------------------------------------------------------
@settings(max_examples=200, deadline=None)
@given(raw=st.one_of(st.sampled_from(_KNOWN_PAYLOADS), st.binary(max_size=64)))
def test_detection_predicate_is_sound(raw):
    """**Validates: Requirements 10.5** (Property 6 — detection soundness).

    The content-derived type is always either ``None`` or a member of the allowed
    set: the helper never reports a type outside the authorized set, and detection
    is deterministic for identical bytes.
    """
    derived = main._detect_image_type(raw)
    assert derived is None or derived in ALLOWED
    # Deterministic: re-running detection on the same bytes yields the same result.
    assert main._detect_image_type(raw) == derived


# ---------------------------------------------------------------------------
# Property B (endpoint): persistence happens iff allowed AND matching.
# ---------------------------------------------------------------------------
@pytest.fixture
def avatar_tmp_dir(tmp_path_factory, monkeypatch):
    """A single temp avatar directory, created once and reused across examples.

    Created at fixture scope (not per-example ``tmp_path``) because Hypothesis
    discourages per-example function-scoped fixtures; the test body clears its
    entries between examples.
    """
    target = tmp_path_factory.mktemp("avatar_soundness")
    monkeypatch.setattr(main, "AVATAR_DIR", target)
    return target


@pytest.fixture
def authed_client(client):
    """Register once so the shared TestClient carries an auth cookie."""
    resp = client.post(
        "/api/v1/auth/register",
        json={
            "email": "upload-soundness@example.com",
            "password": "password123",
            "display_name": "Upload Soundness",
        },
    )
    assert resp.status_code == 201, resp.text
    return client


@settings(
    max_examples=60,
    deadline=None,
    suppress_health_check=[HealthCheck.function_scoped_fixture],
)
@given(payload=_upload_strategy)
def test_upload_persists_iff_allowed_and_matching(authed_client, avatar_tmp_dir, payload):
    """**Validates: Requirements 10.5** (Property 6 — Upload-soundness).

    For every generated ``(raw_bytes, declared_content_type)`` pair, the avatar
    endpoint persists a file in ``AVATAR_DIR`` *iff* the content-derived type is
    allowed and matches the declared type; in every rejected case the directory
    count is unchanged (nothing is written).
    """
    raw, declared = payload

    # Reset the upload directory so each example starts from a clean, empty state.
    for entry in avatar_tmp_dir.iterdir():
        entry.unlink()
    assert list(avatar_tmp_dir.iterdir()) == []

    expected_accept = _reference_accepts(raw, declared)

    response = authed_client.post(
        AVATAR_URL,
        files={"file": ("upload.bin", raw, declared)},
    )

    persisted = list(avatar_tmp_dir.iterdir())

    if expected_accept:
        assert response.status_code == 200, response.text
        # Exactly one file written, and the returned URL points at it.
        assert len(persisted) == 1, persisted
        avatar_url = response.json()["avatar_url"]
        assert avatar_url.startswith("/uploads/avatars/")
        assert persisted[0].name == avatar_url.rsplit("/", 1)[-1]
    else:
        # Core of Property 6: a rejected upload persists NOTHING.
        assert response.status_code == 400, response.text
        assert response.json()["error"]["code"] in {
            "INVALID_IMAGE_CONTENT",
            "INVALID_IMAGE_TYPE",
            "IMAGE_TYPE_MISMATCH",
        }
        assert persisted == [], persisted
