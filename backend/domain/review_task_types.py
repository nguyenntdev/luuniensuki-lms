"""Review task types and cognitive domain models for LN-03 dual-mode learning.

Defines the core domain representations for balancing retrieval practice
(factual recall) with generative learning (historical explanation) in the
Vietnamese heritage LMS curriculum (Cửu Đỉnh / Triều Nguyễn).
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CognitiveTaskType(str, Enum):
    """Cognitive task taxonomy distinguishing retrieval from generative practice."""
    FACTUAL_RECALL = "factual_recall"
    SEQUENCE_ORDERING = "sequence_ordering"
    SOURCE_CRITIQUE = "source_critique"
    HISTORICAL_EXPLANATION = "historical_explanation"


class TaskEligibilityStatus(str, Enum):
    """Eligibility classification result for review item scheduling."""
    ELIGIBLE = "eligible"
    BLOCKED_PREREQUISITE = "blocked_prerequisite"
    BLOCKED_SOURCE = "blocked_source"
    POSTPONED_NOT_DUE = "postponed_not_due"
    REJECTED_INVALID = "rejected_invalid"


class ReviewDecision(str, Enum):
    """Formal policy decision codes for LN-03."""
    SCHEDULE_ELIGIBLE = "schedule_eligible"
    ASSIGN_FACT_RETRIEVAL = "assign_fact_retrieval"
    POSTPONE = "postpone"
    REJECT_INVALID_SCHEDULER = "reject_invalid_scheduler"
    BLOCK_EXPLANATION = "block_explanation"


class ReviewCard(BaseModel):
    """Review item state including memory parameters and source verification."""
    id: str
    difficulty: float = Field(default=5.0, ge=1.0, le=10.0)
    stability_days: float = Field(default=1.0, ge=0.0)
    target_retention: float = Field(default=0.9, ge=0.5, le=1.0)
    state: str = "review"
    due_utc: str
    last_review_utc: Optional[str] = None
    source_verified: bool = True


class ContentDescriptor(BaseModel):
    """Target learning object / relic in the curriculum."""
    id: str
    label: Optional[str] = None
    type: Optional[str] = None


class GenerativeTaskDescriptor(BaseModel):
    """Requirements for historical explanation generation tasks."""
    task_type: CognitiveTaskType = CognitiveTaskType.HISTORICAL_EXPLANATION
    fact_prerequisite_mastered: bool
    source_verified: bool
    workload_budget: float = 1.0


class ReviewAssignment(BaseModel):
    """Output assignment generated by the scheduler."""
    decision: ReviewDecision
    task_type: CognitiveTaskType
    generative_assigned: bool
    reason_codes: List[str]
    review_burden: float
    task_type_coverage: float
